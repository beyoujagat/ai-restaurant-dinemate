"""
Catalog Store (Phase 2).
Provides access to the SQLite restaurant catalog, faceted search options
(locations, cuisines, budget hints), and candidate filtering.
"""

from __future__ import annotations

import json
import logging
import os
from pathlib import Path
import sqlite3
from typing import Any

from app.catalog.filters import apply_candidate_filters
from app.domain.budget import get_budget_label
from app.domain.models import Preference, Restaurant

logger = logging.getLogger(__name__)


class CatalogNotFoundError(FileNotFoundError):
    """Raised when the SQLite database has not yet been generated by ingest."""
    pass


class CatalogStore:
    """
    SQLite-backed store for restaurant catalog data.
    """

    def __init__(self, db_path: Path | str | None = None) -> None:
        if db_path:
            self.db_path = Path(db_path)
        else:
            env_path = os.getenv("CATALOG_DB_PATH", "data/processed/restaurants.sqlite")
            # If path is relative, resolve relative to project root
            p = Path(env_path)
            if not p.is_absolute():
                # Walk up to repo root (assuming store.py is at backend/app/catalog/store.py)
                root_dir = Path(__file__).resolve().parents[3]
                self.db_path = root_dir / env_path
            else:
                self.db_path = p

        if not self.db_path.exists():
            raise CatalogNotFoundError(
                f"Catalog database not found at {self.db_path}. "
                "Please run data ingestion first (`python -m app.catalog.ingest`)."
            )

    def _get_connection(self) -> sqlite3.Connection:
        conn = sqlite3.connect(str(self.db_path))
        conn.row_factory = sqlite3.Row
        return conn

    @staticmethod
    def _row_to_restaurant(row: sqlite3.Row | dict[str, Any]) -> Restaurant:
        """Helper to deserialize SQLite row into Restaurant domain model."""
        d = dict(row)

        # Deserialize JSON arrays
        for field in ("cuisines", "rest_types", "listed_types", "dishes_liked", "review_snippets"):
            val = d.get(field)
            if isinstance(val, str):
                try:
                    d[field] = json.loads(val)
                except Exception:
                    d[field] = []
            elif not isinstance(val, list):
                d[field] = []

        # Coerce booleans
        d["online_order"] = bool(d.get("online_order"))
        d["book_table"] = bool(d.get("book_table"))

        return Restaurant(**d)

    def get_restaurant_by_id(self, restaurant_id: str) -> Restaurant | None:
        """Fetch a single restaurant by its 16-char ID."""
        with self._get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute("SELECT * FROM restaurants WHERE id = ?", (restaurant_id,))
            row = cursor.fetchone()
            if row is None:
                return None
            return self._row_to_restaurant(row)

    def get_restaurants_by_ids(self, ids: list[str]) -> list[Restaurant]:
        """Fetch multiple restaurants preserving the requested ID order."""
        if not ids:
            return []

        placeholders = ",".join("?" for _ in ids)
        with self._get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute(f"SELECT * FROM restaurants WHERE id IN ({placeholders})", ids)
            rows = cursor.fetchall()

        by_id = {row["id"]: self._row_to_restaurant(row) for row in rows}
        return [by_id[rid] for rid in ids if rid in by_id]

    def get_all_restaurants(self, limit: int | None = None) -> list[Restaurant]:
        """Fetch all restaurant records (or up to limit)."""
        with self._get_connection() as conn:
            cursor = conn.cursor()
            query = "SELECT * FROM restaurants"
            if limit:
                query += f" LIMIT {int(limit)}"
            cursor.execute(query)
            return [self._row_to_restaurant(row) for row in cursor.fetchall()]

    def list_locations(self) -> list[str]:
        """Return sorted list of Bangalore neighborhoods/locations."""
        with self._get_connection() as conn:
            cursor = conn.cursor()
            # Try locations facet table first
            cursor.execute("SELECT neighborhood FROM locations WHERE neighborhood != '' ORDER BY neighborhood")
            rows = cursor.fetchall()
            if rows:
                return [r[0] for r in rows]
            # Fallback to distinct from restaurants
            cursor.execute("SELECT DISTINCT neighborhood FROM restaurants WHERE neighborhood != '' ORDER BY neighborhood")
            return [r[0] for r in cursor.fetchall()]

    def list_cuisines(self) -> list[str]:
        """Return sorted list of distinct cuisines."""
        with self._get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute("SELECT cuisine FROM cuisines WHERE cuisine != '' ORDER BY cuisine")
            rows = cursor.fetchall()
            if rows:
                return [r[0] for r in rows]
            cursor.execute("SELECT DISTINCT cuisine FROM restaurant_cuisine ORDER BY cuisine")
            return [r[0] for r in cursor.fetchall()]

    def get_meta_options(self) -> dict[str, Any]:
        """
        Faceted dropdown options for the API and frontend:
        locations, cuisines, budget bands with cost hints, rating choices.
        """
        return {
            "locations": self.list_locations(),
            "cuisines": self.list_cuisines(),
            "budget_labels": {
                "low": get_budget_label("low"),
                "medium": get_budget_label("medium"),
                "high": get_budget_label("high"),
            },
            "rating_choices": [3.0, 3.5, 4.0, 4.5],
        }

    def query_candidates(
        self,
        preference: Preference,
        candidate_limit: int | None = None,
    ) -> tuple[list[Restaurant], dict[str, int]]:
        """
        Filter candidates matching the given preferences.
        Uses indexed SQL pre-filtering on location/budget where possible,
        then runs the full deterministic filter & pre-ranking pipeline.
        """
        sql_parts = ["SELECT * FROM restaurants WHERE 1=1"]
        params: list[Any] = []

        # If location specified, pre-filter with indexed neighborhood OR listed_city
        if preference.location:
            loc = preference.location.strip()
            sql_parts.append("AND (LOWER(neighborhood) = LOWER(?) OR LOWER(listed_city) = LOWER(?))")
            params.extend([loc, loc])

        with self._get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute(" ".join(sql_parts), params)
            candidates = [self._row_to_restaurant(row) for row in cursor.fetchall()]

        # If SQL pre-filter didn't match (e.g. partial substring location), fetch broader
        if not candidates and preference.location:
            with self._get_connection() as conn:
                cursor = conn.cursor()
                cursor.execute(
                    "SELECT * FROM restaurants WHERE LOWER(neighborhood) LIKE ? OR LOWER(listed_city) LIKE ?",
                    (f"%{preference.location.lower()}%", f"%{preference.location.lower()}%"),
                )
                candidates = [self._row_to_restaurant(row) for row in cursor.fetchall()]

        # Run complete in-memory deterministic filter pipeline (order: location -> budget -> cuisine -> rating -> extras)
        shortlist, counts = apply_candidate_filters(candidates, preference, candidate_limit)
        return shortlist, counts
